function openInMatlabBrowser(pdfPath, outdir, jsCore, jsWorker)
    % genera un viewer independiente y lo abre en el navegador integrado de MATLAB
    fid = fopen(pdfPath,'r'); bytes = fread(fid, Inf, '*uint8'); fclose(fid);
    if exist('matlab.net.base64encode','file'), b64 = matlab.net.base64encode(bytes);
    else, b64 = local_base64encode(bytes); end
    b64 = string(b64);

    jsCoreURI   = ['file:///' strrep(jsCore,  '\','/')];   jsCoreURI   = regexprep(jsCoreURI,   '^file:/+', 'file:///');
    jsWorkerURI = ['file:///' strrep(jsWorker,'\','/')];   jsWorkerURI = regexprep(jsWorkerURI, '^file:/+', 'file:///');

    htmlParts = [
        "<!doctype html><html><head><meta charset=""utf-8"">"
        "<style>html,body{margin:0;height:100%;overflow:auto;background:#fff;} #wrap{width:100%;height:100%;display:flex;align-items:flex-start;justify-content:center;} canvas{max-width:100%;height:auto;background:#fff;}</style>"
        "<script src=""" + string(jsCoreURI) + """></script>"
        "<script>pdfjsLib.GlobalWorkerOptions.workerSrc=""" + string(jsWorkerURI) + """;</script>"
        "</head><body><div id=""wrap""><canvas id=""cv""></canvas></div>"
        "<script>"
        "function b64ToUint8(b64){var raw=atob(b64);var len=raw.length;var u8=new Uint8Array(len);for(var i=0;i<len;i++){u8[i]=raw.charCodeAt(i);}return u8;}"
        "const data = b64ToUint8(""" + b64 + """);"
        "const canvas = document.getElementById('cv'); const ctx = canvas.getContext('2d'); const scale = 1.5;"
        "pdfjsLib.getDocument({data: data}).promise.then(pdf=>pdf.getPage(1)).then(page=>{"
        "  const v = page.getViewport({scale}); canvas.width=v.width; canvas.height=v.height;"
        "  return page.render({canvasContext: ctx, viewport: v}).promise;"
        "});"
        "</script></body></html>"
    ];
    viewer2 = fullfile(outdir, 'viewer_matlabbrowser.html');
    fid = fopen(viewer2,'w'); fwrite(fid, char(strjoin(htmlParts,newline)), 'char'); fclose(fid);

    url = ['file:///' strrep(viewer2,'\','/')];  url = regexprep(url,'^file:/+','file:///');
    web(url, '-new');   % navegador integrado de MATLAB (no el del sistema)
end


function s = local_base64encode(u8)
    % u8: uint8 vector → base64 (sin saltos de línea)
    table = ['A':'Z','a':'z','0':'9','+','/'];
    pad = mod(3 - mod(numel(u8),3), 3);
    if pad>0, u8 = [u8; zeros(pad,1,'uint8')]; end
    u8 = reshape(u8,3,[]);
    v = uint32(u8(1,:))*65536 + uint32(u8(2,:))*256 + uint32(u8(3,:));
    b1 = bitshift(bitand(v, uint32(16711680)),-18);
    b2 = bitshift(bitand(v, uint32(258048)),  -12);
    b3 = bitshift(bitand(v, uint32(4032)),    -6);
    b4 = bitand(v, uint32(63));
    idx = [b1;b2;b3;b4] + 1;
    s = reshape(table(double(idx)),1,[]);
    if pad>0, s(end-pad+1:end) = '='; end
end

