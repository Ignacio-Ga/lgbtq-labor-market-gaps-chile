function S = preview_latex_table(latex_code)
% PREVIEW_LATEX_TABLE  (versión 1-argumento, con carrusel embebido)
% Uso:
%   preview_latex_table(latex_code1);
%   preview_latex_table(latex_code2);
%   preview_latex_table(latex_code3);
%
% Cada llamada compila y agrega la tabla al visor (uihtml) con flechas
% para navegar entre las previsualizaciones de la sesión.
%
% Requiere: pdflatex (MiKTeX/TeX Live) disponible. Sin pdflatex, no rompe:
% guarda .tex, avisa y muestra un mensaje en la UI.

    % ---------- validación ----------
    if nargin < 1 || isempty(latex_code)
        warning('preview_latex_table: falta el código LaTeX.');
        if nargout>0, S = struct(); end
        return;
    end
    if isstring(latex_code)
        latex_code = char(join(latex_code,newline));
    elseif ~ischar(latex_code)
        error('El argumento debe ser char o string con \\begin{table}...\\end{table}.');
    end

    % ---------- estado persistente (UI + historial) ----------
    persistent APP
    if isempty(APP) || ~isstruct(APP) || ~isvalidField(APP,'fig') || ~isvalid(APP.fig)
        APP = initApp();
    end

    % ---------- directorios ----------
    baseDir = APP.baseDir;  % FolderData si existe; sino pwd
    outdir  = APP.outdir;   % baseDir/_latex_preview
    if ~exist(baseDir,'dir'), mkdir(baseDir); end
    if ~exist(outdir,'dir'), mkdir(outdir); end

    % ---------- nombre base: hash del contenido para evitar duplicados ----------
    hash = compute_hash(latex_code);              % md5 de latex_code
    bname = ['tbl_' hash(1:10)];                  % nombre compacto
    texfile = fullfile(outdir, [bname '.tex']);
    pdffile = fullfile(outdir, [bname '.pdf']);
    logfile = fullfile(outdir, [bname '.log']);

    % ---------- escribir .tex mínimamente autocontenido ----------
    doc = [ ...
        '%% Auto-generated by preview_latex_table', newline, ...
        '\documentclass[11pt]{article}', newline, ...
        '\usepackage[margin=2cm]{geometry}', newline, ...
        '\usepackage{booktabs,threeparttable,hyperref,caption,float}', newline, ...
        '\captionsetup{margin=0.5cm}', newline, ...
        '\begin{document}', newline, ...
        latex_code, newline, ...
        '\end{document}', newline ];
    fid = fopen(texfile,'w'); assert(fid>0,'No se pudo abrir %s',texfile);
    fwrite(fid, doc, 'char'); fclose(fid);

    % ---------- compilar (si hay pdflatex) ----------
    pdflatex = local_find_pdflatex();
    compiledOK = false;
    if isempty(pdflatex)
        msg = sprintf(['No se encontró "pdflatex".\nSe guardó el .tex en:\n%s\n' ...
                       'Instala MiKTeX/TeX Live o agrega pdflatex al PATH.'], texfile);
        compiledOK = false;
    else
        cwd = pwd; cd(outdir);
        try
            [~,log1] = system(sprintf('"%s" -interaction=nonstopmode "%s"', pdflatex, [bname '.tex']));
            [~,log2] = system(sprintf('"%s" -interaction=nonstopmode "%s"', pdflatex, [bname '.tex']));
        catch ME
            cd(cwd); rethrow(ME);
        end
        cd(cwd);
        fid = fopen(logfile,'w'); if fid>0, fwrite(fid,[log1 newline log2],'char'); fclose(fid); end
        compiledOK = isfile(pdffile);
        if ~compiledOK
            msg = sprintf('Compilación LaTeX falló. Revisa el log: %s', logfile);
        end
    end

    % ---------- registrar entrada en historial ----------
    entry = struct('name', bname, 'tex', texfile, 'pdf', '', 'log', logfile);
    if compiledOK, entry.pdf = pdffile; end

    % reemplazar si ya existía mismo hash, si no, agregar
    idx = find(strcmp({APP.items.name}, bname), 1);
    if isempty(idx)
        APP.items(end+1) = entry; %#ok<AGROW>
        APP.idx = numel(APP.items);
    else
        APP.items(idx) = entry;
        APP.idx = idx;
    end

    % ---------- actualizar visor UI ----------
    if compiledOK
    showPDF(APP, APP.idx);  % <<--- ESTA ES LA LLAMADA CLAVE
    if isfield(APP,'statusLbl') && isvalid(APP.statusLbl)
        set(APP.statusLbl,'Text',sprintf('Mostrando %d/%d', APP.idx, numel(APP.items)));
    end
    else
        % aviso si no compiló
        msg = sprintf('Compilación LaTeX no disponible.\nRevisa: %s', logfile);
        if isfield(APP,'html') && isvalid(APP.html)
            APP.html.HTMLSource = sprintf([ ...
              '<!doctype html><html><head><meta charset="utf-8">', ...
              '<style>html,body{margin:0;height:100%%;display:flex;align-items:center;justify-content:center;font-family:Arial;}</style>', ...
              '</head><body><div style="max-width:70%%;text-align:center;">', ...
              '<h2 style="margin:0;color:#b00;">No se pudo mostrar el PDF</h2>', ...
              '<p style="margin-top:8px;line-height:1.4;">%s</p>', ...
              '</div></body></html>'], strrep(msg,newline,'<br>'));
        end
    end

    % ---------- salida opcional ----------
    if nargout>0
        S = struct('dir',outdir,'tex',texfile,'pdf',entry.pdf,'log',logfile, ...
                   'index',APP.idx,'count',numel(APP.items));
    end

    % ---------- guardar estado ----------
    %setappdata(0,'__CASEN_PREVIEW_APP__',APP);  % redundante, por si se recrea persistent

end

% ================= helpers internos =================

function APP = initApp()
    % baseDir desde FolderData si existe en base workspace
    baseDir = pwd;
    try
        if evalin('base','exist(''FolderData'',''var'')')
            bd = evalin('base','FolderData');
            if isstring(bd), bd = char(bd); end
            if ischar(bd) && ~isempty(bd), baseDir = bd; end
        end
    catch, end
    outdir = fullfile(baseDir,'_latex_preview');
    if ~exist(outdir,'dir'), mkdir(outdir); end

    % construir UI
    fig = uifigure('Name','Vista previa de tablas (LaTeX → PDF)','Position',[100 100 1000 700],'Color','w');

    gl = uigridlayout(fig,[2 1]);
    gl.RowHeight   = {40,'1x'};
    gl.ColumnWidth = {'1x'};

    top = uigridlayout(gl,[1 5]);  % [prev | label | spacer | label2 | next]
    top.ColumnWidth = {60, 160, '1x', 140, 60};

    btnPrev = uibutton(top,'Text','⬅︎','ButtonPushedFcn',@(src,evt)nav(-1));
    btnPrev.Layout.Column = 1;

    statusLbl = uilabel(top,'Text','Sin elementos','HorizontalAlignment','center','FontWeight','bold');
    statusLbl.Layout.Column = 2;

    infoLbl = uilabel(top,'Text','Use ⬅︎ y ➡︎ para navegar','HorizontalAlignment','right','FontAngle','italic');
    infoLbl.Layout.Column = 4;

    btnNext = uibutton(top,'Text','➡︎','ButtonPushedFcn',@(src,evt)nav(+1));
    btnNext.Layout.Column = 5;

    html = uihtml(gl,'HTMLSource','<div style="font-family:Arial;padding:2em;">Listo para previsualizar tablas.</div>');
    html.Layout.Row = 2; html.Layout.Column = 1;

    APP = struct;
    APP.baseDir = baseDir;
    APP.outdir  = outdir;
    APP.fig     = fig;
    APP.html    = html;
    APP.statusLbl = statusLbl;
    APP.items   = struct('name',{},'tex',{},'pdf',{},'log',{});
    APP.idx     = 0;

    % Callbacks usan nested functions para acceder a APP
    function nav(step)
        if isempty(APP.items), return; end
        APP.idx = max(1,min(APP.idx + step, numel(APP.items)));
        showPDF(APP, APP.idx);
        set(APP.statusLbl,'Text',sprintf('Mostrando %d/%d', APP.idx, numel(APP.items)));
    end
end

function showPDF(APP, k)
    if k<1 || k>numel(APP.items), return; end
    pdfPath = APP.items(k).pdf;
    if isempty(pdfPath) || ~isfile(pdfPath)
        APP.html.HTMLSource = '<div style="font-family:Arial;padding:2em;color:#b00;">PDF no disponible.</div>';
        return;
    end
    uri = char(java.io.File(pdfPath).toURI.toString());
    html = sprintf([ ...
        '<!doctype html><html><head><meta charset="utf-8">', ...
        '<style>html,body{margin:0;height:100%%;} ', ...
        'iframe{border:0;width:100%%;height:100%%;}</style>', ...
        '</head><body><iframe src="%s"></iframe></body></html>'], uri);
    APP.html.HTMLSource = html;
end

function tf = isvalidField(S, f)
    tf = isstruct(S) && isfield(S,f) && ~isempty(S.(f));
end

function h = compute_hash(txt)
    % md5 hash mediante Java (sin dependencias externas)
    md = java.security.MessageDigest.getInstance('MD5');
    md.update(uint8(txt));
    h  = typecast(md.digest,'uint8');
    h  = lower(reshape(dec2hex(h,2).',1,[])); % hex string
end

function exe = local_find_pdflatex()
    exe = local_find_exe({'pdflatex.exe','pdflatex'});
    if ~isempty(exe), return; end
    if ispc
        cands = {};
        userLocal = getenv('LOCALAPPDATA');
        if ~isempty(userLocal)
            cands{end+1} = fullfile(userLocal,'Programs','MiKTeX','miktex','bin','x64','pdflatex.exe');
            cands{end+1} = fullfile(userLocal,'Programs','MiKTeX','miktex','bin','pdflatex.exe');
        end
        cands{end+1} = 'C:\Program Files\MiKTeX\miktex\bin\x64\pdflatex.exe';
        cands{end+1} = 'C:\Program Files (x86)\MiKTeX\miktex\bin\pdflatex.exe';
        cands{end+1} = 'C:\texlive\2025\bin\win32\pdflatex.exe';
        cands{end+1} = 'C:\texlive\2024\bin\win32\pdflatex.exe';
        for i=1:numel(cands)
            if exist(cands{i},'file')
                exe = cands{i};
                setenv('PATH',[fileparts(exe) pathsep getenv('PATH')]); % habilita para futuras llamadas
                return;
            end
        end
        % Registro MiKTeX (opcional)
        try
            root = winqueryreg('HKEY_LOCAL_MACHINE','SOFTWARE\MiKTeX.org\MiKTeX','InstallRoot');
            p1 = fullfile(root,'miktex','bin','x64','pdflatex.exe');
            p2 = fullfile(root,'miktex','bin','pdflatex.exe');
            for cand = {p1,p2}
                if exist(cand{1},'file')
                    exe = cand{1};
                    setenv('PATH',[fileparts(exe) pathsep getenv('PATH')]);
                    return;
                end
            end
        catch, end
    end
end

function exe = local_find_exe(cands)
    exe = '';
    for i=1:numel(cands)
        c = cands{i};
        if ispc, [s,p] = system(sprintf('where %s',c));
        else,     [s,p] = system(sprintf('which %s',c));
        end
        if s==0
            lines = strtrim(strsplit(p,newline));
            exe = lines{1}; return;
        end
    end
function uri = local_file_uri(p)
    % Devuelve una URI file:/// robusta para un path local (con espacios/acentos)
    if exist('matlab.net.URI','class') ...
       && any(strcmp(methods('matlab.net.URI'),'fromFilename'))
        uri = char(matlab.net.URI.fromFilename(p).string);
    else
        % Compatibilidad con versiones sin matlab.net.URI.fromFilename
        uri = char(java.io.File(p).toURI.toString());
    end
end
