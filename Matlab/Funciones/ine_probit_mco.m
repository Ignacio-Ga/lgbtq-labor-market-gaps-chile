% 4. Pesos, estratos y conglomerados
% -------------------------------------------------------------------------
%
% La Encuesta Web Diversidades no tiene el diseño probabilístico de CASEN.
% Por ello:
%
%   peso    = 1 para cada observación
%   estrato = un único estrato
%   cluster = cada persona es su propio conglomerado
%
% Esto permite utilizar las funciones existentes, pero los resultados no
% deben interpretarse como estimaciones poblacionales representativas.

