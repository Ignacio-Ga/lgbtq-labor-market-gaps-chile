%% ------------------------------------------------------------------------
%  Preparación de variables explicativas
% -------------------------------------------------------------------------

% Sexo asignado al nacer:
% m02_var05:
%   1 = masculino
%   2 = femenino
%
% Variable binaria:
%   1 = masculino asignado al nacer
%   0 = femenino asignado al nacer
% NaN = respuesta inválida o faltante

ine.sexo_nacer = NaN(height(ine),1);

idxSexoNacer = ismember(ine.m02_var05, [1,2]);

ine.sexo_nacer(idxSexoNacer) = ...
    double(ine.m02_var05(idxSexoNacer) == 1);


%% ------------------------------------------------------------------------
% Tramos de edad
% -------------------------------------------------------------------------
%
% tr_edad:
%   1 = 14 a 17
%   2 = 18 a 29
%   3 = 30 a 59
%   4 = 60 o más
%
% Categoría base: 18 a 29 años

ine.edad_30_59 = NaN(height(ine),1);
ine.edad_60mas = NaN(height(ine),1);

idxEdadValida = ismember(ine.tr_edad, [2,3,4]);

ine.edad_30_59(idxEdadValida) = ...
    double(ine.tr_edad(idxEdadValida) == 3);

ine.edad_60mas(idxEdadValida) = ...
    double(ine.tr_edad(idxEdadValida) == 4);


%% ------------------------------------------------------------------------
% Nivel educacional
% -------------------------------------------------------------------------
%
% ed_nivel:
%   1 = sin primaria o primaria incompleta
%   2 = primaria completa
%   3 = secundaria completa
%   4 = técnica
%   5 = universitaria completa
%
% Categoría base:
%   sin primaria o primaria incompleta

ine.edu_primaria     = NaN(height(ine),1);
ine.edu_secundaria   = NaN(height(ine),1);
ine.edu_tecnica      = NaN(height(ine),1);
ine.edu_universitaria = NaN(height(ine),1);

idxEducacionValida = ismember(ine.ed_nivel, 1:5);

ine.edu_primaria(idxEducacionValida) = ...
    double(ine.ed_nivel(idxEducacionValida) == 2);

ine.edu_secundaria(idxEducacionValida) = ...
    double(ine.ed_nivel(idxEducacionValida) == 3);

ine.edu_tecnica(idxEducacionValida) = ...
    double(ine.ed_nivel(idxEducacionValida) == 4);

ine.edu_universitaria(idxEducacionValida) = ...
    double(ine.ed_nivel(idxEducacionValida) == 5);


%% ------------------------------------------------------------------------
% Pueblos originarios
% -------------------------------------------------------------------------

ine.pueblos_indigenas = NaN(height(ine),1);

idxIndigenaValido = ismember(ine.m01_var07, [1,2]);

ine.pueblos_indigenas(idxIndigenaValido) = ...
    double(ine.m01_var07(idxIndigenaValido) == 1);


%% ------------------------------------------------------------------------
% Agrupación alternativa de orientaciones sexuales
% -------------------------------------------------------------------------
%
% lg:
%   gay o lesbiana
%
% b:
%   bisexual
%
% other_os:
%   pansexual, asexual u otra orientación
%
% Heterosexual queda como categoría base.

ine.other_os = NaN(height(ine),1);

idxOrientacionValida = ismember(ine.m02_var09, 1:7);

ine.other_os(idxOrientacionValida) = double( ...
    ismember(ine.m02_var09(idxOrientacionValida), [4,5,7]));


