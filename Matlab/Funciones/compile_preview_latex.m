function out = preview_latex_table(latex_table_code, varargin)
% PREVIEW_LATEX_TABLE  (versión mínima)
% Uso básico:
%   preview_latex_table(latex_code);
%
% - latex_code: string con \begin{table}...\end{table} (de export_models_table).
% - Sin argumentos de ruta: crea una carpeta temporal bajo el directorio actual.
% - Compila con pdflatex y muestra la tabla (PNG) en una figura. Si no hay
%   Ghostscript, abre el PDF con el visor por defecto del sistema.
%
% Opcionales (Name,Value):
%   'DPI'        : resolución al rasterizar (default 250)
%   'ShowFigure' : true/false (default true)

    % Opciones opcionales
    p = inputParser;
    addParameter(p,'DPI',250,@(x)isnumeric(x)&&x>0);
    addParameter(p,'ShowFigure',true,@(x)islogical(x)||ismember(x,[0,1]));
    parse(p,varargin{:});
    DPI = p.Results.DPI; ShowFigure = p.Results.ShowFigure;

    % Directorio temporal local (bajo el directorio de trabajo actual)
    stamp   = datestr(now,'yyyymmdd_HHMMSSFFF');
    outdir  = fullfile(pwd, ['_latex_preview_', stamp]);
    if ~exist(outdir,'dir'); mkdir(outdir); end
    basename = 'preview_table';
    texfile  = fullfile(outdir, [basename '.tex']);
    pdffile  = fullfile(outdir, [basename '.pdf']);
    pngfile  = fullfile(outdir, [basename '.png']);
    logfile  = fullfile(outdir, [basename '.log']);

    % Documento LaTeX mínimo
    doc = strjoin({ ...
        '%% Auto-generated by preview_latex_table', ...
        '\documentclass[11pt]{article}', ...
        '\usepackage[margin=2cm]{geometry}', ...
        '\usepackage{booktabs,threeparttable,hyperref,caption,float}', ...
        '\captionsetup{margin=0.5cm}', ...
        '\begin{document}', ...
        latex_table_code, ...
        '\end{document}'}, newline);

    % Escribir .tex
    fid = fopen(texfile,'w'); assert(fid>0,'No se pudo abrir %s',texfile);
    fwrite(fid, doc, 'char'); fclose(fid);

    % Localizar ejecutables
    pdflatex = local_find_exe({'pdflatex.exe','pdflatex'});
    gs       = local_find_exe({'gswin64c.exe','gswin32c.exe','gs'}); % Ghostscript opcional

    if isempty(pdflatex)
        error(['No se encontró "pdflatex" en el PATH.' newline ...
               'Instala TeX (MiKTeX/TeX Live/MacTeX) o agrega pdflatex al PATH.']);
    end

    % Compilar (dos pasadas)
    cwd = pwd; cd(outdir);
    try
        [st1,log1] = system(sprintf('"%s" -interaction=nonstopmode "%s"', pdflatex, [basename '.tex']));
        [st2,log2] = system(sprintf('"%s" -interaction=nonstopmode "%s"', pdflatex, [basename '.tex']));
    catch ME
        cd(cwd); rethrow(ME);
    end
    cd(cwd);
    fid = fopen(logfile,'w'); if fid>0, fwrite(fid, [log1 newline log2],'char'); fclose(fid); end
    if ~exist(pdffile,'file'); error('Compilación LaTeX falló. Revisa el log: %s', logfile); end

    % Si hay Ghostscript, rasterizar a PNG y mostrar
    if ~isempty(gs)
        cmd = sprintf('"%s" -dSAFER -dBATCH -dNOPAUSE -sDEVICE=pngalpha -r%d -sOutputFile="%s" "%s"', ...
                       gs, DPI, pngfile, pdffile);
        [stg,logg] = system(cmd); %#ok<ASGLU>
        if exist(pngfile,'file') && ShowFigure
            img = imread(pngfile);
            figure('Name','LaTeX Table Preview','NumberTitle','off','Color','w');
            imshow(img); axis image off;
            title('LaTeX Table Preview','Interpreter','none');
        elseif ~exist(pngfile,'file')
            % Si no se creó PNG, abrir PDF
            local_open(pdffile);
        end
    else
        % Sin Ghostscript: abrir PDF
        local_open(pdffile);
    end

    % Salida (opcional)
    if nargout>0
        out = struct('dir',outdir,'tex',texfile,'pdf',pdffile,'png',pngfile,'log',logfile);
    end
end

% ----------------- helpers locales -----------------
function exe = local_find_exe(candidates)
    exe = '';
    for i=1:numel(candidates)
        c = candidates{i};
        if ispc
            [s,p] = system(sprintf('where %s', c));
        else
            [s,p] = system(sprintf('which %s', c));
        end
        if s==0
            lines = strtrim(strsplit(p,newline));
            exe = lines{1};
            return;
        end
    end
end

function local_open(pathfile)
    if ispc
        system(sprintf('start "" "%s"', pathfile));
    elseif ismac
        system(sprintf('open "%s"', pathfile));
    else
        system(sprintf('xdg-open "%s"', pathfile));
    end
end
